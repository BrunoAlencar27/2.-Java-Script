let n1=2;
let n2=3;

console.log(n1+=n2);//Adiciona e atribui
console.log(n1-=n2);//Subtrai e atribui 
console.log(n1*=n2);//Multiplica e atribui
console.log(n1/=n2);//Divide e atribui
console.log(n1%=n2);//Módulo e atribui
console.log(n1**=n2);//Expoenencia e atribui

