let n1=2;
let n2=3;
console.log(n1+n2);//Operador de soma
console.log(n1-n2);//Operador de subtração
console.log(n1*n2);//Operador de multiplicação
console.log(n1/n2);//Operador de divisão
console.log(n1%n2);//Operador de módulo
console.log(n1**n2);//Operador de exponenciação
console.log(n1++);//Operador de incremento em 1
console.log(n2--);//Operador de decremento em 1
